/**
 * Bundle the ESM sources under src/ into the single classic-script bundle the
 * DSH Web module loader serves as `client.js`.
 *
 * The DSH combo script concatenates each plugin's client entry and executes it
 * as a classic script, so the entry cannot contain ESM imports. This tiny
 * bundler keeps src/ as the readable and directly testable source of truth.
 *
 * Usage: node scripts/build-client.mjs [--check]
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const modules = [
  'src/identity-core.js',
  'src/identity-client.js',
  'src/model-catalog.js',
  'src/model-groups.js',
  'src/model-storage.js',
  'src/settings-preferences.js',
  'src/feature-settings.js',
  'src/i18n.js',
  'src/styles.js',
  'src/model-selector.js',
  'src/workspace-flat-toggle.js',
  'src/toolbox-data.js',
  'src/settings-panel.js',
  'src/features.js',
]

function resolveModule(fromId, specifier) {
  if (!specifier.startsWith('.')) {
    throw new Error(`Only relative imports are supported in src/: ${fromId} -> ${specifier}`)
  }
  const resolved = relative(packageRoot, resolve(packageRoot, dirname(fromId), specifier)).replaceAll('\\', '/')
  return resolved
}

function parseImportNames(clause) {
  const inner = clause.trim().replace(/^\{/u, '').replace(/\}$/u, '')
  const names = inner
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean)
    .map((part) => {
      const [original, alias] = part.split(/\s+as\s+/u).map((value) => value.trim())
      return alias ? `${original}: ${alias}` : original
    })
  return `{ ${names.join(', ')} }`
}

function transform(id, source) {
  const exported = new Set()
  let code = source

  code = code.replace(
    /^import\s+([\s\S]*?)\s+from\s+(['"])([^'"]+)\2;?[ \t]*$/gmu,
    (match, clause, quote, specifier) => {
      const target = resolveModule(id, specifier)
      if (clause.trim().startsWith('{')) {
        return `const ${parseImportNames(clause)} = __require(${JSON.stringify(target)})`
      }
      const defaultName = clause.trim()
      if (/^[A-Za-z_$][\w$]*$/u.test(defaultName)) {
        return `const ${defaultName} = __require(${JSON.stringify(target)}).default`
      }
      throw new Error(`Unsupported import form in ${id}: ${match}`)
    },
  )

  code = code.replace(/^export\s+(async\s+)?function\s+([A-Za-z_$][\w$]*)/gmu, (match, asyncKeyword, name) => {
    exported.add(name)
    return `${asyncKeyword ?? ''}function ${name}`
  })
  code = code.replace(/^export\s+class\s+([A-Za-z_$][\w$]*)/gmu, (match, name) => {
    exported.add(name)
    return `class ${name}`
  })
  code = code.replace(/^export\s+(const|let|var)\s+([A-Za-z_$][\w$]*)/gmu, (match, keyword, name) => {
    exported.add(name)
    return `${keyword} ${name}`
  })

  if (/^\s*export\s+/mu.test(code)) {
    throw new Error(`Unsupported export remains in ${id}`)
  }
  if (/^\s*import\s+/mu.test(code)) {
    throw new Error(`Unsupported import remains in ${id}`)
  }

  return {
    code: code.trimEnd(),
    exports: [...exported],
  }
}

const transformed = modules.map((id) => {
  // Normalize CRLF so a Windows checkout (core.autocrlf=true) produces exactly
  // the LF bundle that is committed instead of a whitespace-only churn.
  const source = readFileSync(resolve(packageRoot, id), 'utf-8').replace(/\r\n?/gu, '\n')
  return { id, ...transform(id, source) }
})

const bundle = `/* Generated by scripts/build-client.mjs. Do not edit by hand. */
window.__ModuleLoader__.load({
  id: 'dsh-toolbox',
  factory(require) {
    const React = require('react')
    const __defs = Object.create(null)
    const __cache = Object.create(null)
    function __require(id) {
      if (__cache[id] !== undefined) return __cache[id]
      const definition = __defs[id]
      if (definition === undefined) throw new Error('dsh-toolbox: unknown internal module ' + id)
      const exports = definition()
      __cache[id] = exports
      return exports
    }
${transformed
  .map(
    ({ id, code, exports }) => `    __defs[${JSON.stringify(id)}] = () => {
${code
  .split('\n')
  .map((line) => (line.length > 0 ? `      ${line}` : ''))
  .join('\n')}
      return { ${exports.join(', ')} }
    }`,
  )
  .join('\n')}
    const { createToolbox } = __require('src/features.js')
    const toolbox = createToolbox({ React })
    return { apply: toolbox.apply, inject: toolbox.inject }
  },
})
`

const target = resolve(packageRoot, 'client.js')
const check = process.argv.includes('--check')
if (check) {
  if (!existsSync(target)) {
    console.error('client.js is missing; run node scripts/build-client.mjs')
    process.exit(1)
  }
  const current = readFileSync(target, 'utf-8').replace(/\r\n?/gu, '\n')
  if (current !== bundle) {
    console.error('client.js is out of date; run node scripts/build-client.mjs')
    process.exit(1)
  }
  console.log('client.js is up to date')
} else {
  writeFileSync(target, bundle, 'utf-8')
  console.log(`wrote client.js (${bundle.length} bytes)`)
}
